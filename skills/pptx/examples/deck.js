/**
 * Starter deck for the pi-pptx skill — copy and adapt.
 *
 * Run:   node examples/deck.js      (writes ./example-deck.pptx)
 * Needs: pptxgenjs (`npm install pptxgenjs`, or a NODE_PATH that has it).
 */
const pptxgen = require("pptxgenjs");

// --- design system: pick before writing slides ------------------------------
const FONT = { head: "Cambria", body: "Calibri" };
const C = {
	ink: "1F2933",
	paper: "FFFFFF",
	navy: "16324F",
	ice: "CADCFC",
	teal: "2A9D8F",
	grey: "5C6B73",
	line: "E5E9EC",
};

const p = new pptxgen();
p.layout = "LAYOUT_WIDE"; // 13.33 x 7.5 in — set BEFORE adding slides
p.title = "Quarterly review";
p.subject = "Example deck generated by the pi-pptx skill";

// 1) Title slide — dark background, takeaway as subtitle.
const s1 = p.addSlide();
s1.background = { color: C.navy };
s1.addText("Quarterly review", {
	x: 0.7, y: 2.5, w: 11.9, h: 1.3,
	fontFace: FONT.head, fontSize: 44, bold: true, color: C.paper, margin: 0,
});
s1.addText("Growth held; the next constraint is capacity", {
	x: 0.7, y: 3.8, w: 11.9, h: 0.6,
	fontFace: FONT.body, fontSize: 20, color: C.ice, margin: 0,
});
s1.addNotes("Open with the single takeaway, then preview the three numbers slide.");

// 2) Stat callouts — big numbers with small labels.
const s2 = p.addSlide();
s2.addText("Three numbers that matter", {
	x: 0.7, y: 0.5, w: 11.9, h: 0.8,
	fontFace: FONT.head, fontSize: 32, bold: true, color: C.ink, margin: 0,
});
const stats = [
	["+18%", "revenue growth vs last quarter"],
	["2.4x", "faster review cycle"],
	["31", "releases shipped"],
];
stats.forEach(([big, small], i) => {
	const x = 0.7 + i * 4.1;
	s2.addText(big, {
		x, y: 2.2, w: 3.6, h: 1.1,
		fontFace: FONT.head, fontSize: 54, bold: true, color: C.teal, margin: 0,
	});
	s2.addText(small, {
		x, y: 3.3, w: 3.6, h: 0.6,
		fontSize: 16, color: C.grey, margin: 0,
	});
});

// 3) Chart slide — native chart + interpretation on the right.
const s3 = p.addSlide();
s3.addText("Volume keeps climbing", {
	x: 0.7, y: 0.5, w: 11.9, h: 0.8,
	fontFace: FONT.head, fontSize: 32, bold: true, color: C.ink, margin: 0,
});
s3.addChart(
	p.ChartType.line,
	[{ name: "requests", labels: ["Q1", "Q2", "Q3", "Q4"], values: [120, 180, 260, 410] }],
	{
		x: 0.7, y: 1.6, w: 7.6, h: 5.2,
		showTitle: false, showLegend: false, showValue: false,
		chartColors: [C.teal], lineDataSymbol: "circle",
		catAxisLabelColor: C.grey, valAxisLabelColor: C.grey,
		catAxisLabelFontSize: 12, valAxisLabelFontSize: 12,
		valGridLine: { color: C.line, size: 1 }, catGridLine: { style: "none" },
	},
);
s3.addText("Requests grew 3.4x across the year. Q4 is the first quarter above planned capacity.", {
	x: 8.6, y: 1.6, w: 4.0, h: 2.4,
	fontSize: 18, color: C.ink, margin: 0, lineSpacingMultiple: 1.2,
});
s3.addNotes("Talk track: emphasize the capacity inflection at Q4, not the raw growth.");

// 4) Table slide — decisions, owners, dates.
const s4 = p.addSlide();
s4.addText("Plan for next quarter", {
	x: 0.7, y: 0.5, w: 11.9, h: 0.8,
	fontFace: FONT.head, fontSize: 32, bold: true, color: C.ink, margin: 0,
});
const head = [
	{ text: "Workstream", options: { bold: true, fill: { color: C.navy }, color: C.paper } },
	{ text: "Owner", options: { bold: true, fill: { color: C.navy }, color: C.paper } },
	{ text: "Done by", options: { bold: true, fill: { color: C.navy }, color: C.paper } },
];
const rows = [
	["Capacity upgrade", "Platform", "Week 3"],
	["Review automation", "Tooling", "Week 5"],
	["Pricing experiment", "Growth", "Week 7"],
];
const body = rows.map((r) => r.map((t) => ({ text: t, options: { color: C.ink } })));
s4.addTable([head, ...body], {
	x: 0.7, y: 1.7, w: 11.9,
	fontFace: FONT.body, fontSize: 15,
	border: { type: "solid", color: C.line, pt: 0.5 },
	rowH: 0.55, valign: "middle", colW: [6.0, 3.0, 2.9],
});

p.writeFile({ fileName: "example-deck.pptx" }).then((f) => console.log("wrote:", f));
